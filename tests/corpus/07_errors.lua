local ok, err = pcall(function() error("boom") end)
print(ok, err)
local ok2, err2 = pcall(function() error({code = 7}) end)
print(ok2, type(err2), err2.code)
local ok3, err3 = pcall(function() local x = nil return x.y end)
print(ok3, err3 ~= nil)
print(pcall(function() return 1, 2 end))
local ok4, v = pcall(function() return select(2, pcall(error)) end)
print(ok4, v)
